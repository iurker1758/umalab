import { useEffect, useState } from "react";
import type { FactorRef, SlotFactor, SlotFactorKind, WatchedSpark } from "../api";
import { SPARK_TYPE_LABELS, SPARK_TYPE_ORDER, sparkId } from "../procs";
// `toggle` is what applies DEFAULT_HUNTING — the default lives in one place
// in the store (#33), and the chooser must not restate it.
import { isWatched, setHunting, toggle } from "../sparks";

// Hand entry for a member's non-pink sparks: a popout that BROWSES the 432
// factors, with the ones you've favourited at the top of it.
//
// It replaces the inline search this file used to be (DECISIONS.md #35,
// reversing #30's "an add-one affordance, not a browser"). That search worked
// perfectly if you already knew a name and not at all otherwise — typing "s"
// returned eight of 309 matches and a line reading "301 more". The popout
// still holds a search box, so the typist's path survives one click behind a
// button; what it adds is a way to find a spark you can't spell.
//
// ADDING is all it does, and adding includes the LEVEL — three buttons per
// row, so a 3★ is one click at the moment you are choosing the spark
// (DECISIONS.md #34). Nothing here can change a chance in the table behind it.
//
// FAVOURITING is a different act from adding, deliberately (#35): a filler
// white you type onto every node must not land in #27's watched block, and a
// row must not move under the pointer that just clicked it.
//
// A roster or lineage pick never needs any of this — hers are decoded from
// the dump — so it only appears on hand-built nodes, which is also why it is
// not offered inside a locked branch.

// The browse sections, in the same order the spark tables group by
// (procs.ts), minus the pink the document doesn't hand-enter. Not "whites
// first" despite whites being 256 of the 432: the sections are headed and
// nothing is hidden, so the reader scrolls rather than losing rows off a cap
// — which is the bias #30 caught, and it does not apply to a list with no
// cap in it.
const BROWSE_KINDS: SlotFactorKind[] = (
  ["white", "unique", "race", "scenario"] as SlotFactorKind[]
).sort((a, b) => SPARK_TYPE_ORDER[a] - SPARK_TYPE_ORDER[b]);

// A row the chooser can offer: a spark from the reference, or one the
// reference doesn't know. Watched keys are deliberately not validated against
// `app/data` (#33) — the reference is regenerated by hand and can run behind
// a dump — so a favourite may resolve to no name and still be perfectly
// addable, its kind being what decides the base rate.
type Option = { kind: SlotFactorKind; key: number; name: string };

const optionOf = (ref: FactorRef): Option => ref;

const unknownOption = (spark: WatchedSpark): Option => ({
  kind: spark.kind,
  key: spark.key,
  // The same degradation ProcPanel uses for a stored spark the reference
  // can't name, rather than a blank row.
  name: `Unknown (${spark.key})`,
});

function SparkRows({
  options,
  held,
  watched,
  watchedFailed,
  busy,
  onAdd,
  onFavourite,
  onHunting,
}: {
  options: Option[];
  held: Set<string>;
  watched: WatchedSpark[];
  watchedFailed: boolean;
  busy: boolean;
  onAdd: (option: Option, stars: number) => void;
  onFavourite: (option: Option) => void;
  onHunting: (option: Option, hunting: boolean) => void;
}) {
  return (
    <ul className="spark-matches">
      {options.map((o) => {
        const fav = isWatched(watched, o.kind, o.key);
        const hunting = watched.find(
          (w) => w.kind === o.kind && w.key === o.key
        )?.hunting;
        return (
          <li key={sparkId({ type: o.kind, key: o.key })}>
            {/* Favouriting is its own control, never a side effect of adding:
                every filler white you type onto a grandparent would otherwise
                land in #27's uncapped block, and the row would climb out from
                under the pointer as the favourites re-sorted. Disabled rather
                than hidden when the list didn't load, so the chooser doesn't
                silently change shape on a fetch failure. */}
            <button
              className={fav ? "spark-fav active" : "spark-fav"}
              aria-pressed={fav}
              aria-label={`Favourite ${o.name}`}
              disabled={watchedFailed || busy}
              onClick={() => onFavourite(o)}
            >
              {fav ? "★" : "☆"}
            </button>
            <span className="spark-hit">
              {/* The kind is part of the identity here, which is why it
                  survives in the chooser after #30 cut it from the proc
                  tables: you are picking BETWEEN kinds, and several race and
                  scenario sparks share wording with skills. */}
              <span className={`proc-kind proc-kind-${o.kind}`}>
                {SPARK_TYPE_LABELS[o.kind]}
              </span>
              {o.name}
            </span>
            {held.has(sparkId({ type: o.kind, key: o.key })) ? (
              // Shown, marked, rather than filtered into silence: finding the
              // right name and getting nothing back reads as "no such spark".
              // The level it was added at lives in the table behind this, with
              // the ✕ that undoes it.
              <span className="spark-held">Added</span>
            ) : (
              // Not a `radiogroup`: these three don't hold a value between
              // them, they are three different add actions. Each names its own
              // outcome, because "3★" alone is meaningless read out of the row
              // it sits in.
              <span className="seg-group" role="group">
                {[1, 2, 3].map((n) => (
                  <button
                    key={n}
                    className="seg"
                    // The spark's identity on the button, so anything driving
                    // this list picks by (kind, key) rather than by the
                    // displayed name — several race and scenario sparks
                    // contain a skill's name as a substring, and the reference
                    // holds two distinct whites both called "Pressure".
                    data-spark={sparkId({ type: o.kind, key: o.key })}
                    data-stars={n}
                    aria-label={`Add ${o.name} at ${n}★`}
                    onClick={() => onAdd(o, n)}
                  >
                    {n}★
                  </button>
                ))}
              </span>
            )}
            {/* The hunting bit, on its own line and only once the row is
                watched. #33 defaults a new favourite to hunting because adding
                is a deliberate pick, and says filler is "one click off at the
                moment you add it" — this is that moment, so the control has to
                be here rather than waiting for #27's surface. Its own line
                because the row already carries a star, a kind tag, a name and
                three buttons, and at 358px (the popout on a 390px phone) a
                fifth control on the line takes the name's width. */}
            {fav && (
              <span className="spark-hunt-line">
                <button
                  className={hunting === true ? "spark-hunt active" : "spark-hunt"}
                  aria-pressed={hunting === true}
                  aria-label={`Hunting ${o.name}`}
                  title="Breeding for this, not just quick to type"
                  disabled={busy}
                  onClick={() => onHunting(o, hunting !== true)}
                >
                  Hunting
                </button>
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}

function ChooserPopout({
  label,
  factors,
  refs,
  watched,
  watchedFailed,
  onAdd,
  onWatched,
  onClose,
}: {
  label: string;
  factors: readonly SlotFactor[];
  refs: readonly FactorRef[];
  watched: WatchedSpark[];
  watchedFailed: boolean;
  onAdd: (option: Option, stars: number) => void;
  onWatched: (next: WatchedSpark[]) => void;
  onClose: () => void;
}) {
  const [query, setQuery] = useState("");
  const [busy, setBusy] = useState(false);
  const [failed, setFailed] = useState(false);
  // WHICH sparks sit in the Favourites section, snapshotted when the popout
  // opens. The live list still drives every ★ and every Hunting pill; only
  // the ordering is frozen. Without this, favouriting a row lifts it out of
  // its kind section and the add buttons you were reaching for are somewhere
  // else — the same "row moves under the pointer that just clicked it"
  // failure #34 spent an entry closing, arriving by a different route. The
  // popout is remounted on every open, so a favourite is at the top the next
  // time you look.
  const [pinned] = useState(
    () => new Set(watched.map((w) => sparkId({ type: w.kind, key: w.key })))
  );

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  const held = new Set(factors.map((f) => sparkId({ type: f.kind, key: f.key })));
  const names = new Map(
    refs.map((r) => [sparkId({ type: r.kind, key: r.key }), r.name])
  );
  const q = query.trim().toLowerCase();
  // One rule for every section: the query filters, the sections and their
  // order never change, and hits rank by where the query lands in the name
  // then alphabetically — which is a no-op when there is no query, the
  // reference arriving sorted by (kind, name) already. Deliberately NOT the
  // order the reference serves under a query: capping that order directly is
  // what returned eight race sparks and hid every white match behind them
  // (#30). Nothing is capped here, so the ranking only decides what you read
  // first, but it decides it the same way.
  const matching = (options: Option[]): Option[] => {
    const hits = options.filter((o) => o.name.toLowerCase().includes(q));
    if (q === "") return hits;
    return hits.sort(
      (a, b) =>
        a.name.toLowerCase().indexOf(q) - b.name.toLowerCase().indexOf(q) ||
        a.name.localeCompare(b.name)
    );
  };

  // Insertion order, oldest first, which is what the store's own `list` gives
  // and what its row ids mean (#33).
  const favourites = matching(
    watched
      .filter((w) => pinned.has(sparkId({ type: w.kind, key: w.key })))
      .map((w) => {
        const name = names.get(sparkId({ type: w.kind, key: w.key }));
        return name === undefined
          ? unknownOption(w)
          : { kind: w.kind, key: w.key, name };
      })
  );
  // A favourite is in the Favourites section and NOWHERE ELSE. Rendering it
  // in its kind section too is the same spark twice on one surface, in two
  // idioms — the duplication #45 deleted the held list to remove, and it
  // arrives here as "which of these two rows did I already star". The
  // snapshot is what decides, so nothing disappears from under the pointer
  // when you favourite it: it stays where it is until the next open.
  const sections = BROWSE_KINDS.map((kind) => ({
    kind,
    options: matching(
      refs
        .filter(
          (r) => r.kind === kind && !pinned.has(sparkId({ type: r.kind, key: r.key }))
        )
        .map(optionOf)
    ),
  })).filter((s) => s.options.length > 0);

  // Non-optimistic: `sparks.ts` returns the list the server ended up with, so
  // the star only moves once the row exists. A failed write leaves it where
  // it was and says so inside the popout, which is over the toast the rest of
  // the page uses.
  const write = async (op: () => Promise<WatchedSpark[]>) => {
    setBusy(true);
    try {
      onWatched(await op());
      setFailed(false);
    } catch {
      setFailed(true);
    } finally {
      setBusy(false);
    }
  };

  const rowProps = {
    held,
    watched,
    watchedFailed,
    busy,
    onAdd,
    onFavourite: (o: Option) => void write(() => toggle(watched, o.kind, o.key)),
    onHunting: (o: Option, hunting: boolean) =>
      void write(() => setHunting(watched, o.kind, o.key, hunting)),
  };

  return (
    <>
      {/* Dismisses on mousedown, not click: Chrome freezes the OS cursor when
          a click unmounts the element under it, which reads as "hover is
          broken" until the next click. The filter panel's popouts do the
          same. */}
      <div className="uma-popout-backdrop" onMouseDown={onClose} />
      <div className="uma-popout spark-popout" role="dialog" aria-label="Add a Spark">
        {/* Sticky, so the query stays reachable while you scroll 432 rows
            past it — that is the difference between a browser and a list you
            have to leave in order to re-query. */}
        <div className="spark-search-band">
          <input
            className="uma-search"
            type="search"
            // Kept as the label the inline search carried, so one box on the
            // page still answers to this node.
            aria-label={`${label} spark search`}
            placeholder="Search Sparks…"
            value={query}
            autoFocus
            onChange={(e) => setQuery(e.target.value)}
          />
        </div>
        {/* The reference is committed and works offline; the favourites are
            server state behind Access. A chooser that can't be browsed
            because a list of favourites didn't load would be the failure
            doing the most damage, so the two are said separately and only the
            favourites go away. */}
        {watchedFailed && (
          <p className="spark-note">
            Couldn't load your favourites — browsing still works.
          </p>
        )}
        {failed && (
          <p className="spark-note spark-note-bad">
            Couldn't save that favourite — try again.
          </p>
        )}
        {favourites.length > 0 && (
          <>
            <div className="spark-group">Favourites</div>
            <SparkRows options={favourites} {...rowProps} />
          </>
        )}
        {sections.map((s) => (
          <div key={s.kind}>
            <div className="spark-group">{SPARK_TYPE_LABELS[s.kind]}</div>
            <SparkRows options={s.options} {...rowProps} />
          </div>
        ))}
        {sections.length === 0 && favourites.length === 0 && (
          <span className="empty">No sparks match.</span>
        )}
      </div>
    </>
  );
}

export function SparkChooser({
  label,
  factors,
  refs,
  watched,
  watchedFailed,
  onChange,
  onWatched,
}: {
  // Distinguishes the choosers on one page for aria/testing, as the pink
  // editor does.
  label: string;
  factors: readonly SlotFactor[];
  refs: readonly FactorRef[];
  watched: WatchedSpark[];
  watchedFailed: boolean;
  onChange: (factors: SlotFactor[]) => void;
  onWatched: (next: WatchedSpark[]) => void;
}) {
  const [open, setOpen] = useState(false);
  // Adding does NOT touch the watched list, in either direction — see the
  // header. The blueprint edit is local and the autosave owns it; a watched
  // row is a round-trip, and coupling them means a spark add can fail because
  // a PUT did.
  const add = (option: Option, stars: number) =>
    onChange([...factors, { kind: option.kind, key: option.key, stars }]);
  return (
    <div className="spark-add">
      {/* No ellipsis: a button that opens a dialog doesn't take one, so the
          mark keeps meaning "in flight" or "unresolved". The box inside keeps
          its own. */}
      <button
        className="spark-open"
        aria-haspopup="dialog"
        aria-expanded={open}
        onClick={() => setOpen(true)}
      >
        Add a Spark
      </button>
      {open && (
        <ChooserPopout
          // Remounted per open, which is what re-snapshots the favourites'
          // order and clears an abandoned query — the panel keeps its position
          // in the tree when you click another ancestor, so a query left
          // behind would follow you there.
          label={label}
          factors={factors}
          refs={refs}
          watched={watched}
          watchedFailed={watchedFailed}
          onAdd={add}
          onWatched={onWatched}
          onClose={() => setOpen(false)}
        />
      )}
    </div>
  );
}
